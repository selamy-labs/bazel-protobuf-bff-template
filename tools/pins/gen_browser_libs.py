"""Writes tools/browser/debs.bzl: the Debian packages the pinned browser needs (spec 005 R1).

  python3 -I tools/pins/gen_browser_libs.py tools/browser/debs.bzl

Resolves the dependency closure of the libraries chrome-headless-shell links, from the bookworm
package indexes. libc6 is left out: the C library comes from the host.
"""
import hashlib
import lzma
import re
import sys
import urllib.request

MIRROR = "https://deb.debian.org"
# The main pool drops superseded versions. The snapshot archive keeps them, so each pin stays fetchable.
SNAPSHOT = "https://snapshot.debian.org/archive/{archive}/20261030T000000Z"
INDEXES = [
    f"{MIRROR}/debian/dists/bookworm/main/binary-amd64/Packages.xz",
    f"{MIRROR}/debian/dists/bookworm-updates/main/binary-amd64/Packages.xz",
    "https://security.debian.org/debian-security/dists/bookworm-security/main/binary-amd64/Packages.xz",
]
ROOTS = [
    "libasound2", "libatk-bridge2.0-0", "libatk1.0-0", "libatspi2.0-0", "libdbus-1-3", "libexpat1",
    "libgbm1", "libglib2.0-0", "libnspr4", "libnss3", "libudev1", "libx11-6", "libxcb1",
    "libxcomposite1", "libxdamage1", "libxext6", "libxfixes3", "libxkbcommon0", "libxrandr2",
    "zlib1g", "libgcc-s1", "libstdc++6",
]
SKIP = {"libc6", "debconf", "debconf-2.0", "dpkg", "install-info", "shared-mime-info", "gcc-12-base",
        "libasound2-data", "xkb-data", "libatk1.0-data", "libglib2.0-data", "x11-common", "cdebconf"}


def packages():
    best = {}
    for url in INDEXES:
        text = lzma.decompress(urllib.request.urlopen(url, timeout=120).read()).decode()
        base = url.split("/dists/")[0]
        for block in text.split("\n\n"):
            fields = dict(re.findall(r"^([A-Za-z0-9-]+): (.*)$", block, re.M))
            if "Package" in fields:
                # Later indexes carry the updates and security fixes.
                best[fields["Package"]] = {**fields, "base": base}
    return best


def main():
    index = packages()
    seen = {}
    queue = list(ROOTS)
    while queue:
        name = queue.pop()
        if name in seen or name in SKIP:
            continue
        package = index.get(name)
        if package is None:
            continue  # A virtual package or an alternative that another name satisfies.
        seen[name] = package
        for group in package.get("Depends", "").split(","):
            first = group.split("|")[0].strip().split(" ")[0].split(":")[0]
            if first:
                queue.append(first)
    with open(sys.argv[1], "w") as out:
        out.write('"""Generated by tools/pins/gen_browser_libs.py. Do not edit."""\n\nDEBS = {\n')
        for name in sorted(seen):
            package = seen[name]
            url = f"{package['base']}/{package['Filename']}"
            archive = "debian-security" if "security" in package["base"] else "debian"
            snapshot = f"{SNAPSHOT.format(archive=archive)}/{package['Filename']}"
            data = urllib.request.urlopen(url, timeout=120).read()
            digest = hashlib.sha256(data).hexdigest()
            assert digest == package["SHA256"], name
            out.write(f'    "{name}": (["{url}", "{snapshot}"], "{digest}"),\n')
        out.write("}\n")


main()
